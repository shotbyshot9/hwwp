/**
 * 사용법을 문서용 줄 목록으로 편다.
 *
 * 절 제목은 그 자체로 한 줄이 되고, 절 사이는 빈 줄로 띄운다. 단축키는 표를 만들 수
 * 없으니 「키 — 뜻」 한 줄로 적는다.
 */
export function usageAsLines(): string[] {
  const lines: string[] = [];
  for (const section of USAGE_SECTIONS) {
    if (lines.length > 0) lines.push('');
    lines.push(section.title);
    for (const p of section.paragraphs ?? []) lines.push(p);
    for (const [key, desc] of section.items ?? []) lines.push(`${key} — ${desc}`);
  }
  return lines;
}
